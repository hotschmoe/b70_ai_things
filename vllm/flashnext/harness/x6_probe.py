"""Exact prompt/token fixtures, C1/C2 long-context latency, reference gate.

Run under cpu-run --quiet while the serving container owns its GPU lease.
References must be generated by Strata tooling, never by this client.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
from bench_latency import identity, post_json, stream_completion

p = argparse.ArgumentParser()
p.add_argument('--base-url', required=True)
p.add_argument('--out', type=Path, required=True)
p.add_argument('--prompts', type=Path, required=True)
p.add_argument('--references', type=Path)
p.add_argument('--alias', default='qwen3.8-flash-next-ista-gsq-rco-iq3-xxs-x6-qsa')
a = p.parse_args()
model = 'hotschmoe-dd'
report = dict(identity=identity(a.base_url, model, a.alias), rows=[])
assert report['identity']['first_ok'] and report['identity']['alias_ok']
refs = json.loads(a.references.read_text()) if a.references else None
for fixture in json.loads(a.prompts.read_text()):
    ids = post_json(a.base_url + '/tokenize', dict(model=model, prompt=fixture['prompt'], add_special_tokens=False), 60)['tokens']
    assert ids == fixture['token_ids'], 'vLLM tokenizer differs from reference fixture'
    solo = [stream_completion(a.base_url, model, fixture['prompt'], fixture['max_tokens'], 1800) for _ in range(2)]
    with ThreadPoolExecutor(max_workers=2) as pool:
        concurrent = list(pool.map(lambda _: stream_completion(a.base_url, model, fixture['prompt'], fixture['max_tokens'], 1800), range(2)))
    row = dict(target_tokens=fixture['target_tokens'], prompt_sha256=fixture['prompt_sha256'],
               solo=solo, concurrent=concurrent, repeat_exact=solo[0]['text'] == solo[1]['text'],
               c2_solo_exact=[r['text'] == solo[0]['text'] for r in concurrent],
               strata_exact=None)
    if refs is not None:
        ref = next(r for r in refs if r['prompt_sha256'] == fixture['prompt_sha256'])
        row['strata_exact'] = all(r['text'] == ref['text'] for r in solo + concurrent)
    report['rows'].append(row)
    a.out.write_text(json.dumps(report, indent=2, ensure_ascii=True) + '\n')
    print('X6_LONG', row['target_tokens'], 'C1', solo[1]['itl_ms'], 'C2', [r['itl_ms'] for r in concurrent], 'repeat', row['repeat_exact'], 'strata', row['strata_exact'], flush=True)
report['strata_gate'] = 'unmeasured' if refs is None else all(r['strata_exact'] for r in report['rows'])
a.out.write_text(json.dumps(report, indent=2, ensure_ascii=True) + '\n')
